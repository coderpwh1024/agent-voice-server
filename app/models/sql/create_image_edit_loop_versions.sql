CREATE TABLE IF NOT EXISTS image_edit_loop_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    image_id BIGINT NOT NULL DEFAULT nextval(pg_get_serial_sequence('image_generation_tasks', 'id')::regclass),
    user_id BIGINT NOT NULL,
    root_image_id BIGINT NOT NULL,
    source_image_id BIGINT NOT NULL,
    version SMALLINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    prompt TEXT NOT NULL,
    model VARCHAR(40) NOT NULL,
    size VARCHAR(9),
    source_file_ids BIGINT[] NOT NULL DEFAULT '{}',
    source_urls TEXT[] NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    provider_task_id VARCHAR(128),
    provider_request_id VARCHAR(128),
    provider_image_url TEXT,
    qiniu_object_key VARCHAR(160),
    image_url TEXT,
    status VARCHAR(24) NOT NULL DEFAULT 'QUEUED',
    error_code VARCHAR(64),
    provider_deadline TIMESTAMPTZ,
    next_poll_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_until TIMESTAMPTZ,
    lease_version BIGINT NOT NULL DEFAULT 0,
    failure_count INTEGER NOT NULL DEFAULT 0,
    loop_exit VARCHAR(8),
    accepted_image_id BIGINT,
    create_by BIGINT NOT NULL,
    update_by BIGINT NOT NULL,
    create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_delete SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_image_edit_loop_versions PRIMARY KEY (id),
    CONSTRAINT fk_image_edit_loop_versions_root_image_id FOREIGN KEY (root_image_id)
        REFERENCES image_generation_tasks (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT uk_image_edit_loop_versions_image_id UNIQUE (image_id),
    CONSTRAINT uk_image_edit_loop_versions_root_image_id_version UNIQUE (root_image_id, version),
    CONSTRAINT uk_image_edit_loop_versions_user_id_idempotency_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_image_edit_loop_versions_ids CHECK (user_id > 0 AND source_image_id > 0),
    CONSTRAINT ck_image_edit_loop_versions_version CHECK (version BETWEEN 1 AND 5),
    CONSTRAINT ck_image_edit_loop_versions_is_delete CHECK (is_delete IN (0, 1)),
    CONSTRAINT ck_image_edit_loop_versions_exit CHECK (
        (loop_exit IS NULL AND accepted_image_id IS NULL)
        OR (loop_exit IS NOT NULL AND loop_exit = 'STOPPED' AND accepted_image_id IS NULL)
        OR (loop_exit IS NOT NULL AND loop_exit = 'ACCEPTED' AND accepted_image_id IS NOT NULL)
    ),
    CONSTRAINT ck_image_edit_loop_versions_model CHECK (model IN (
        'qwen-image-3.0-pro', 'qwen-image-3.0', 'qwen-image-2.1-pro', 'qwen-image-2.1-turbo'
    )),
    CONSTRAINT ck_image_edit_loop_versions_status CHECK (status IN (
        'QUEUED', 'SUBMITTING', 'PENDING', 'RUNNING', 'STORING', 'SUCCEEDED',
        'FAILED', 'SUBMISSION_UNKNOWN', 'CANCELED'
    )),
    CONSTRAINT ck_image_edit_loop_versions_references CHECK (
        cardinality(source_file_ids) <= 2
        AND array_position(source_file_ids, NULL) IS NULL
        AND array_position(source_urls, NULL) IS NULL
        AND cardinality(source_urls) = cardinality(source_file_ids) + 1
    ),
    CONSTRAINT ck_image_edit_loop_versions_provider_task CHECK (
        status NOT IN ('PENDING', 'RUNNING', 'STORING', 'SUCCEEDED')
        OR (provider_task_id IS NOT NULL AND provider_deadline IS NOT NULL)
    ),
    CONSTRAINT ck_image_edit_loop_versions_provider_url CHECK (
        (status = 'STORING') = (provider_image_url IS NOT NULL)
    ),
    CONSTRAINT ck_image_edit_loop_versions_stored CHECK (
        (status = 'SUCCEEDED') = (image_url IS NOT NULL AND qiniu_object_key IS NOT NULL)
        AND (image_url IS NULL) = (qiniu_object_key IS NULL)
    ),
    CONSTRAINT ck_image_edit_loop_versions_counters CHECK (lease_version >= 0 AND failure_count >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_image_edit_loop_versions_provider_task_id
    ON image_edit_loop_versions (provider_task_id) WHERE provider_task_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_image_edit_loop_versions_next_poll_time_image_id
    ON image_edit_loop_versions (next_poll_time, image_id)
    WHERE is_delete = 0 AND status IN ('QUEUED', 'SUBMITTING', 'PENDING', 'RUNNING', 'STORING');
CREATE INDEX IF NOT EXISTS idx_image_edit_loop_versions_user_active
    ON image_edit_loop_versions (user_id)
    WHERE is_delete = 0 AND status IN ('QUEUED', 'SUBMITTING', 'PENDING', 'RUNNING', 'STORING');
CREATE INDEX IF NOT EXISTS idx_image_edit_loop_versions_user_history
    ON image_edit_loop_versions (user_id, create_time DESC, root_image_id DESC)
    WHERE version = 1;

CREATE OR REPLACE VIEW image_work_queue AS
    SELECT id, user_id, status, next_poll_time, is_delete, false AS is_loop
    FROM image_generation_tasks
    UNION ALL
    SELECT image_id, user_id, status, next_poll_time, is_delete, true AS is_loop
    FROM image_edit_loop_versions;

