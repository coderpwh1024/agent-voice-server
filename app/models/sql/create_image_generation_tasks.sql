CREATE TABLE IF NOT EXISTS image_generation_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    prompt VARCHAR(4000) NOT NULL,
    model VARCHAR(32) NOT NULL,
    size VARCHAR(9),
    source_image_id BIGINT,
    source_file_ids BIGINT[] NOT NULL DEFAULT '{}',
    source_urls TEXT[] NOT NULL DEFAULT '{}',
    edit_depth INTEGER NOT NULL DEFAULT 0,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    provider_task_id VARCHAR(128),
    provider_request_id VARCHAR(128),
    provider_image_url TEXT,
    qiniu_object_key VARCHAR(160),
    image_url TEXT,
    status VARCHAR(24) NOT NULL DEFAULT 'QUEUED',
    error_code VARCHAR(64),
    provider_deadline TIMESTAMPTZ,
    next_poll_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_until TIMESTAMPTZ,
    lease_version BIGINT NOT NULL DEFAULT 0,
    failure_count INTEGER NOT NULL DEFAULT 0,
    create_by BIGINT NOT NULL,
    update_by BIGINT NOT NULL,
    create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_delete SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_image_generation_tasks PRIMARY KEY (id),
    CONSTRAINT fk_image_generation_tasks_source_image_id FOREIGN KEY (source_image_id)
        REFERENCES image_generation_tasks (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_image_generation_tasks_user_id CHECK (user_id > 0),
    CONSTRAINT ck_image_generation_tasks_is_delete CHECK (is_delete IN (0, 1)),
    CONSTRAINT ck_image_generation_tasks_model CHECK (model IN (
        'qwen-image-3.0-pro', 'qwen-image-3.0', 'qwen-image-2.1-pro', 'qwen-image-2.1-turbo'
    )),
    CONSTRAINT ck_image_generation_tasks_status CHECK (status IN (
        'QUEUED', 'SUBMITTING', 'PENDING', 'RUNNING', 'STORING', 'SUCCEEDED',
        'FAILED', 'SUBMISSION_UNKNOWN', 'CANCELED'
    )),
    CONSTRAINT ck_image_generation_tasks_references CHECK (
        cardinality(source_file_ids) + (source_image_id IS NOT NULL)::INTEGER <= 3
        AND array_position(source_file_ids, NULL) IS NULL
        AND array_position(source_urls, NULL) IS NULL
        AND cardinality(source_urls) =
            cardinality(source_file_ids) + (source_image_id IS NOT NULL)::INTEGER
        AND (source_image_id IS NULL AND edit_depth = 0 OR source_image_id IS NOT NULL AND edit_depth > 0)
    ),
    CONSTRAINT ck_image_generation_tasks_provider_task CHECK (
        status NOT IN ('PENDING', 'RUNNING', 'STORING', 'SUCCEEDED')
        OR (provider_task_id IS NOT NULL AND provider_deadline IS NOT NULL)
    ),
    CONSTRAINT ck_image_generation_tasks_provider_url CHECK (
        (status = 'STORING') = (provider_image_url IS NOT NULL)
    ),
    CONSTRAINT ck_image_generation_tasks_stored CHECK (
        (status = 'SUCCEEDED') = (image_url IS NOT NULL AND qiniu_object_key IS NOT NULL)
        AND (image_url IS NULL) = (qiniu_object_key IS NULL)
    ),
    CONSTRAINT ck_image_generation_tasks_counters CHECK (lease_version >= 0 AND failure_count >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_image_generation_tasks_user_id_idempotency_key
    ON image_generation_tasks (user_id, idempotency_key) WHERE is_delete = 0;
CREATE INDEX IF NOT EXISTS idx_image_generation_tasks_deleted_idempotency_key
    ON image_generation_tasks (user_id, idempotency_key) WHERE is_delete = 1;
CREATE UNIQUE INDEX IF NOT EXISTS uk_image_generation_tasks_provider_task_id
    ON image_generation_tasks (provider_task_id) WHERE provider_task_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_image_generation_tasks_user_id_id
    ON image_generation_tasks (user_id, id DESC) WHERE is_delete = 0;
CREATE INDEX IF NOT EXISTS idx_image_generation_tasks_source_image_id
    ON image_generation_tasks (source_image_id) WHERE source_image_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_image_generation_tasks_next_poll_time_id
    ON image_generation_tasks (next_poll_time, id)
    WHERE is_delete = 0 AND status IN ('QUEUED', 'SUBMITTING', 'PENDING', 'RUNNING', 'STORING');

